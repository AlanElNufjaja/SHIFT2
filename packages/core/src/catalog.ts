export const CROP_BY_ID: Record<string, Crop> = Object.fromEntries(CROPS.map((c) => [c.id, c]));

export function getCrop(id: string, catalog: Crop[] = CROPS): Crop {
  const c = catalog.find((x) => x.id === id) ?? CROP_BY_ID[id];
  if (!c) throw new Error(`Unknown crop id: ${id}`);
  return c;
}

export const MAIN_CROPS = CROPS.filter((c) => c.role === 'main');
export const COVER_CROPS = CROPS.filter((c) => c.category === 'cover');

/** Merge user/local market overrides into the catalog (non-destructive). */
export function applyMarketOverrides(
  catalog: Crop[],
  overrides: Record<string, Partial<Pick<Crop['market'], 'price' | 'potentialYield' | 'costPerHa'>> & { priceSource?: string }>,
): Crop[] {
  return catalog.map((c) => {
    const o = overrides[c.id];
    if (!o) return c;
    return { ...c, market: { ...c.market, ...o } };
  });
}
